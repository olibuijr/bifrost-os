//! bifrost long-press variant tables for the keyboard: accents on letters,
//! currency, quotes and punctuation variants on the numbers/symbols pages.

/// The variants a long press on `base` offers (lower case; the base itself
/// is added by the popup).
pub fn variants(base: &str) -> &'static [&'static str] {
    match base {
        "a" => &["á", "à", "â", "ä", "æ", "ã", "å", "ā"],
        "e" => &["é", "è", "ê", "ë", "ē", "ė", "ę"],
        "i" => &["í", "ì", "î", "ï", "ī", "į"],
        "o" => &["ó", "ò", "ô", "ö", "ø", "õ", "œ", "ō"],
        "u" => &["ú", "ù", "û", "ü", "ū"],
        "y" => &["ý", "ÿ"],
        "d" => &["ð"],
        "t" => &["þ"],
        "c" => &["ç", "ć", "č"],
        "n" => &["ñ", "ń"],
        "s" => &["ß", "š", "ś"],
        "z" => &["ž", "ź", "ż"],
        "l" => &["ł"],
        "ð" => &["d"],
        "þ" => &["t"],
        "æ" => &["a", "ä"],
        "ö" => &["o", "ø", "œ"],
        "$" => &["€", "£", "¥", "₩", "₹", "¢"],
        "€" => &["$", "£", "¥", "₩", "₹", "¢"],
        "£" => &["$", "€", "¥", "₩", "₹", "¢"],
        "\"" => &["“", "”", "„", "»", "«"],
        "'" => &["‘", "’", "‚", "‹", "›"],
        "-" => &["–", "—", "•"],
        "—" => &["–", "-", "•"],
        "." => &["…"],
        "?" => &["¿"],
        "!" => &["¡"],
        "&" => &["§"],
        "%" => &["‰"],
        "0" => &["°"],
        "=" => &["≠", "≈"],
        _ => &[],
    }
}
