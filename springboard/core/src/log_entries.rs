//! The entry kinds of the unified log beyond a plain message: boundaries (`OSLogEntryBoundary`), activities
//! (`OSLogEntryActivity`), payload entries built from a format string (`OSLogEntryWithPayload`) and the message
//! components they are split into (`OSLogMessageComponent`).
//!
//! These are pure models. `log.rs` still produces the plain `LogEntry` from the journal and the in-process ring;
//! `Entry` wraps it next to the other kinds so one sequence can hold all of them. Positions and enumeration over a
//! sequence are in `log_cursor.rs`.
//!
//! Format strings use the placeholder syntax of the system logger: `%d`, `%u`, `%x`, `%f`, `%s`, `%@`, `%p`, each
//! optionally with a privacy option block `%{public}@` or `%{private}s` (values are private unless marked public).
//! `%P` is this module's own spec for a byte sequence, shown as hex.
//! The official case list of `OSLogMessageComponent.ArgumentCategory` is not in the abstract-level documentation
//! this was checked against, so the categories here are this module's own (integer, unsigned, double, text, data).
use crate::log::{Level, LogEntry};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::SystemTime;

/// The metadata that partitions a sequence of entries (`OSLogEntryBoundary`): a process start or a log rotation.
#[derive(Clone, Debug, PartialEq)]
pub struct Boundary {
    pub date: SystemTime,
    pub process: String,
    pub pid: u32,
}

/// An entry generated by an activity event (`OSLogEntryActivity`). `parent` links it to the activity it runs in.
#[derive(Clone, Debug, PartialEq)]
pub struct Activity {
    pub date: SystemTime,
    pub id: u64,
    pub parent: Option<u64>,
    pub name: String,
    pub process: String,
    pub pid: u32,
}

/// One value passed to a format string.
#[derive(Clone, Debug, PartialEq)]
pub enum Argument {
    Int(i64),
    Uint(u64),
    Double(f64),
    Text(String),
    Data(Vec<u8>),
}

/// The category of argument a placeholder expects.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ArgumentCategory {
    Integer,
    Unsigned,
    Double,
    Text,
    Data,
}

/// Whether a value is shown in clear. Values are private unless the format marks them public.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Privacy {
    Public,
    Private,
}

/// One `%...` placeholder of a format string.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Placeholder {
    pub category: ArgumentCategory,
    pub privacy: Privacy,
    /// The conversion character as written (`d`, `@`, ...).
    pub spec: char,
}

/// `OSLogMessageComponent`: the literal text before a placeholder and the placeholder itself. The last component
/// of a message may have no placeholder and carries only the trailing text.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Component {
    pub format_substring: String,
    pub placeholder: Option<Placeholder>,
}

/// `OSLogEntryWithPayload`: an entry made from a format string and its arguments.
#[derive(Clone, Debug, PartialEq)]
pub struct Payload {
    pub entry: LogEntry,
    pub format: String,
    pub components: Vec<Component>,
    pub args: Vec<Argument>,
}

/// One entry of a sequence: a plain message, a payload, an activity or a boundary.
#[derive(Clone, Debug, PartialEq)]
pub enum Entry {
    Log(LogEntry),
    Payload(Payload),
    Activity(Activity),
    Boundary(Boundary),
}

impl From<LogEntry> for Entry {
    fn from(e: LogEntry) -> Entry {
        Entry::Log(e)
    }
}

impl Entry {
    pub fn date(&self) -> SystemTime {
        match self {
            Entry::Log(e) => e.date,
            Entry::Payload(p) => p.entry.date,
            Entry::Activity(a) => a.date,
            Entry::Boundary(b) => b.date,
        }
    }
}

impl Argument {
    /// `argumentInt64Value`: the value as a signed integer, when it is one.
    pub fn int64(&self) -> Option<i64> {
        match self {
            Argument::Int(v) => Some(*v),
            Argument::Uint(v) => i64::try_from(*v).ok(),
            _ => None,
        }
    }

    /// `argumentUInt64Value`: the value as an unsigned integer, when it is one.
    pub fn uint64(&self) -> Option<u64> {
        match self {
            Argument::Uint(v) => Some(*v),
            Argument::Int(v) => u64::try_from(*v).ok(),
            _ => None,
        }
    }

    /// `argumentDoubleValue`: integers convert, text and data do not.
    pub fn double(&self) -> Option<f64> {
        match self {
            Argument::Double(v) => Some(*v),
            Argument::Int(v) => Some(*v as f64),
            Argument::Uint(v) => Some(*v as f64),
            _ => None,
        }
    }

    /// `argumentStringValue`: only text is a string.
    pub fn string(&self) -> Option<&str> {
        match self {
            Argument::Text(s) => Some(s),
            _ => None,
        }
    }

    fn category(&self) -> ArgumentCategory {
        match self {
            Argument::Int(_) => ArgumentCategory::Integer,
            Argument::Uint(_) => ArgumentCategory::Unsigned,
            Argument::Double(_) => ArgumentCategory::Double,
            Argument::Text(_) => ArgumentCategory::Text,
            Argument::Data(_) => ArgumentCategory::Data,
        }
    }

    fn text(&self) -> String {
        match self {
            Argument::Int(v) => v.to_string(),
            Argument::Uint(v) => v.to_string(),
            Argument::Double(v) => format!("{v}"),
            Argument::Text(s) => s.clone(),
            Argument::Data(d) => d.iter().map(|b| format!("{b:02x}")).collect(),
        }
    }
}

/// Splits a format string into components. `%%` is a literal percent sign. Length modifiers (`h`, `l`, `ll`, `z`,
/// `j`, `t`, `L`) are accepted and ignored. A privacy block is `{public}` or `{private}` before the conversion.
pub fn parse_format(format: &str) -> Result<Vec<Component>, String> {
    let mut out = Vec::new();
    let mut text = String::new();
    let mut chars = format.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            text.push(c);
            continue;
        }
        if chars.peek() == Some(&'%') {
            chars.next();
            text.push('%');
            continue;
        }
        let mut privacy = Privacy::Private;
        if chars.peek() == Some(&'{') {
            chars.next();
            let mut opts = String::new();
            loop {
                match chars.next() {
                    Some('}') => break,
                    Some(o) => opts.push(o),
                    None => return Err(format!("unclosed option block in {format:?}")),
                }
            }
            privacy = match opts.trim() {
                "public" => Privacy::Public,
                "private" => Privacy::Private,
                other => return Err(format!("unknown option {other:?} in {format:?}")),
            };
        }
        while matches!(chars.peek(), Some('h' | 'l' | 'z' | 'j' | 't' | 'L')) {
            chars.next();
        }
        let spec = chars.next().ok_or_else(|| format!("placeholder at the end of {format:?}"))?;
        let category = match spec {
            'd' | 'i' => ArgumentCategory::Integer,
            'u' | 'x' | 'X' | 'o' | 'p' => ArgumentCategory::Unsigned,
            'f' | 'e' | 'E' | 'g' | 'G' | 'a' => ArgumentCategory::Double,
            's' | '@' => ArgumentCategory::Text,
            'P' => ArgumentCategory::Data,
            other => return Err(format!("unknown conversion %{other} in {format:?}")),
        };
        out.push(Component { format_substring: std::mem::take(&mut text), placeholder: Some(Placeholder { category, privacy, spec }) });
    }
    out.push(Component { format_substring: text, placeholder: None });
    Ok(out)
}

/// Renders components with their arguments. A private value is written as `<private>` unless `show` is set.
/// The argument count and each argument's category must match the placeholders.
pub fn render(components: &[Component], args: &[Argument], show: bool) -> Result<String, String> {
    let mut out = String::new();
    let mut next = args.iter();
    for c in components {
        out.push_str(&c.format_substring);
        let Some(p) = &c.placeholder else { continue };
        let arg = next.next().ok_or("fewer arguments than placeholders")?;
        if arg.category() != p.category {
            return Err(format!("argument for %{} has the wrong type", p.spec));
        }
        if p.privacy == Privacy::Private && !show {
            out.push_str("<private>");
        } else {
            out.push_str(&arg.text());
        }
    }
    if next.next().is_some() {
        return Err("more arguments than placeholders".into());
    }
    Ok(out)
}

impl Payload {
    /// Builds a payload entry. The message of `entry` is replaced by the rendering with private values hidden.
    pub fn new(mut entry: LogEntry, format: &str, args: Vec<Argument>) -> Result<Payload, String> {
        let components = parse_format(format)?;
        entry.message = render(&components, &args, false)?;
        Ok(Payload { entry, format: format.to_string(), components, args })
    }

    /// The message with every value shown, for a reader that is allowed to see private data.
    pub fn show_private(&self) -> Result<String, String> {
        render(&self.components, &self.args, true)
    }
}

/// Splits a sequence at its boundaries. Each returned slice holds the entries between two boundaries; the boundary
/// entries themselves are not returned.
pub fn sequences(entries: &[Entry]) -> Vec<&[Entry]> {
    let mut out = Vec::new();
    let mut start = 0;
    for (i, e) in entries.iter().enumerate() {
        if let Entry::Boundary(_) = e {
            out.push(&entries[start..i]);
            start = i + 1;
        }
    }
    out.push(&entries[start..]);
    out
}

static ACTIVITY_SEQ: AtomicU64 = AtomicU64::new(1);

/// A new activity identifier. The high 32 bits are the process id and the low 32 bits count within the process, so
/// identifiers from different processes do not collide.
pub fn new_activity_id() -> u64 {
    let seq = ACTIVITY_SEQ.fetch_add(1, Ordering::Relaxed) & 0xffff_ffff;
    (u64::from(std::process::id()) << 32) | seq
}

/// The chain of activities from `id` up to its root, `id` first. Walks the parents found in `activities` and stops
/// at an unknown parent or when a cycle would repeat.
pub fn activity_chain(activities: &[Activity], id: u64) -> Vec<u64> {
    let mut chain = vec![id];
    let mut cur = id;
    while let Some(parent) = activities.iter().find(|a| a.id == cur).and_then(|a| a.parent) {
        if chain.contains(&parent) {
            break;
        }
        chain.push(parent);
        cur = parent;
    }
    chain
}

#[cfg(test)]
mod tests {
    use super::*;

    use std::time::{Duration, UNIX_EPOCH};

    fn entry(secs: u64, msg: &str) -> LogEntry {
        LogEntry {
            date: UNIX_EPOCH + Duration::from_secs(secs),
            process: "notes".into(),
            pid: 42,
            subsystem: "is.olibuijr.notes".into(),
            category: "sync".into(),
            level: Level::Notice,
            message: msg.into(),
        }
    }

    #[test]
    fn format_string_splits_into_components_and_escapes_percent() {
        let c = parse_format("100%% of %{public}@ has %d items").unwrap();
        assert_eq!(c.len(), 2);
        assert_eq!(c[0].format_substring, "100% of ");
        let p = c[0].placeholder.clone().unwrap();
        assert_eq!((p.category, p.privacy, p.spec), (ArgumentCategory::Text, Privacy::Public, '@'));
        assert_eq!(c[1].format_substring, " has ");
        assert_eq!(c[1].placeholder.as_ref().unwrap().category, ArgumentCategory::Integer);
        assert_eq!(c[1].placeholder.as_ref().unwrap().privacy, Privacy::Private);
        assert!(parse_format("plain text").unwrap()[0].placeholder.is_none());
    }

    #[test]
    fn bad_format_strings_are_refused() {
        assert!(parse_format("oops %q").unwrap_err().contains("unknown conversion"));
        assert!(parse_format("open %{secret}@").unwrap_err().contains("unknown option"));
        assert!(parse_format("dangling %").is_err());
        assert!(parse_format("unclosed %{public").is_err());
    }

    #[test]
    fn payload_hides_private_values_and_shows_public_ones() {
        let p = Payload::new(
            entry(10, ""),
            "opened %{public}s for %d",
            vec![Argument::Text("notes.txt".into()), Argument::Int(7)],
        )
        .unwrap();
        assert_eq!(p.entry.message, "opened notes.txt for <private>");
        assert_eq!(p.show_private().unwrap(), "opened notes.txt for 7");
    }

    #[test]
    fn mismatched_or_missing_arguments_are_refused() {
        let wrong = Payload::new(entry(1, ""), "count %d", vec![Argument::Text("x".into())]);
        assert!(wrong.unwrap_err().contains("wrong type"));
        assert!(Payload::new(entry(1, ""), "%d %d", vec![Argument::Int(1)]).is_err());
        assert!(Payload::new(entry(1, ""), "%d", vec![Argument::Int(1), Argument::Int(2)]).is_err());
    }

    #[test]
    fn argument_accessors_convert_only_sensible_values() {
        assert_eq!(Argument::Uint(5).int64(), Some(5));
        assert_eq!(Argument::Uint(u64::MAX).int64(), None);
        assert_eq!(Argument::Int(-1).uint64(), None);
        assert_eq!(Argument::Int(3).double(), Some(3.0));
        assert_eq!(Argument::Text("a".into()).double(), None);
        assert_eq!(Argument::Text("a".into()).string(), Some("a"));
        assert_eq!(Argument::Data(vec![0xab, 0x01]).string(), None);
    }

    #[test]
    fn boundaries_partition_a_sequence() {
        let b = Entry::Boundary(Boundary { date: UNIX_EPOCH, process: "notes".into(), pid: 42 });
        let seq = vec![Entry::from(entry(1, "a")), Entry::from(entry(2, "b")), b, Entry::from(entry(3, "c"))];
        let parts = sequences(&seq);
        assert_eq!(parts.len(), 2);
        assert_eq!(parts[0].len(), 2);
        assert_eq!(parts[1].len(), 1);
        assert_eq!(sequences(&[]).len(), 1);
    }

    #[test]
    fn activity_chain_follows_parents_and_stops_at_cycles() {
        let act = |id, parent| Activity { date: UNIX_EPOCH, id, parent, name: format!("a{id}"), process: "p".into(), pid: 1 };
        let acts = vec![act(1, None), act(2, Some(1)), act(3, Some(2)), act(4, Some(4))];
        assert_eq!(activity_chain(&acts, 3), vec![3, 2, 1]);
        assert_eq!(activity_chain(&acts, 1), vec![1]);
        assert_eq!(activity_chain(&acts, 4), vec![4]);
        assert_eq!(activity_chain(&acts, 9), vec![9]);
    }

    #[test]
    fn activity_ids_are_unique_and_carry_the_process_id() {
        let a = new_activity_id();
        let b = new_activity_id();
        assert_ne!(a, b);
        assert_eq!(a >> 32, u64::from(std::process::id()));
    }

    #[test]
    fn entry_dates_and_log_conversion() {
        let e: Entry = entry(99, "hi").into();
        assert_eq!(e.date(), UNIX_EPOCH + std::time::Duration::from_secs(99));
        assert_eq!(e.date().duration_since(UNIX_EPOCH).unwrap().as_secs(), 99);
    }
}
