#!/usr/bin/env python3
"""Generates springboard/apps/clock-desktop/src/clock/land.rs, the coastline the Clock's World Clock map fills.

usage: tools/gen-world-land.py LAND_GEOJSON

LAND_GEOJSON is Natural Earth's 1:110m land polygons, version 5.1.2:
    https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
    sha256 9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9
Natural Earth data is in the public domain (https://www.naturalearthdata.com/about/terms-of-use/), so the generated
outline ships with the app with no conditions. Every ring (outer rings and holes; the map fills them even-odd) is kept,
with each vertex rounded to a tenth of a degree.
"""
import hashlib
import json
import os
import sys

SHA256 = "9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "springboard", "apps", "clock-desktop", "src", "clock", "land.rs")


def rings(geojson):
    for feature in geojson["features"]:
        g = feature["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            for ring in poly:
                pts = [(round(lon * 10), round(lat * 10)) for lon, lat in ring]
                if len(pts) > 1 and pts[0] == pts[-1]:
                    pts.pop()  # the fill closes the ring
                out = []
                for p in pts:
                    if not out or out[-1] != p:
                        out.append(p)
                if len(out) >= 3:
                    yield out


def main():
    raw = open(sys.argv[1], "rb").read()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        sys.exit("the land polygons do not match the pinned SHA-256")
    all_rings = list(rings(json.loads(raw)))
    lines = [
        "//! The land outline the World Clock map fills: Natural Earth 1:110m land polygons (version 5.1.2), public domain",
        "//! (https://www.naturalearthdata.com/about/terms-of-use/). Generated by tools/gen-world-land.py; do not edit.",
        "",
        "/// Vertex count of each ring, in order through `POINTS`.",
        "pub const RINGS: &[u16] = &[",
    ]
    lens = [str(len(r)) for r in all_rings]
    for i in range(0, len(lens), 24):
        lines.append("    " + ", ".join(lens[i:i + 24]) + ",")
    lines += ["];", "", "/// Longitude and latitude of every vertex, in tenths of a degree.", "pub const POINTS: &[[i16; 2]] = &["]
    flat = [f"[{lon}, {lat}]" for r in all_rings for lon, lat in r]
    for i in range(0, len(flat), 10):
        lines.append("    " + ", ".join(flat[i:i + 10]) + ",")
    lines.append("];")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{OUT}: {len(all_rings)} rings, {len(flat)} points")


if __name__ == "__main__":
    main()
