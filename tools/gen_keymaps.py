#!/usr/bin/env python3
"""Generate springboard/src/installer/keymaps_data.rs from the system's xkb data (libxkbcommon).

For each layout: the character a key types at level 0..3 (plain, shift, altgr, shift+altgr) for the
evdev codes a typing user needs. Dead keys are emitted as combining marks ('\\u{300}' grave, ...) and
composed in Rust. Run on a machine with xkeyboard-config; the output is checked in.
"""
import ctypes, sys
from pathlib import Path

X = ctypes.CDLL("libxkbcommon.so.0")
X.xkb_context_new.restype = ctypes.c_void_p
X.xkb_keymap_new_from_names.restype = ctypes.c_void_p
X.xkb_keymap_new_from_names.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_int]
X.xkb_keymap_key_get_syms_by_level.argtypes = [ctypes.c_void_p, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint32, ctypes.POINTER(ctypes.POINTER(ctypes.c_uint32))]
X.xkb_keymap_key_get_syms_by_level.restype = ctypes.c_int
X.xkb_keysym_to_utf32.argtypes = [ctypes.c_uint32]
X.xkb_keysym_to_utf32.restype = ctypes.c_uint32
X.xkb_keysym_get_name.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]

class Names(ctypes.Structure):
    _fields_ = [(n, ctypes.c_char_p) for n in ("rules", "model", "layout", "variant", "options")]

# (id, display name, xkb layout, xkb variant, console keymap, language code of the layout)
LAYOUTS = [
    ("us", "U.S.", "us", "", "us"), ("us-intl", "U.S. International", "us", "intl", "us-acentos"),
    ("dvorak", "Dvorak", "us", "dvorak", "dvorak"), ("colemak", "Colemak", "us", "colemak", "us"),
    ("gb", "British", "gb", "", "uk"), ("is", "Icelandic", "is", "", "is-latin1"),
    ("de", "German", "de", "", "de-latin1"), ("fr", "French", "fr", "", "fr-latin9"),
    ("es", "Spanish", "es", "", "es"), ("it", "Italian", "it", "", "it"),
    ("se", "Swedish", "se", "", "sv-latin1"), ("no", "Norwegian", "no", "", "no-latin1"),
    ("dk", "Danish", "dk", "", "dk-latin1"), ("fi", "Finnish", "fi", "", "fi"),
    ("nl", "Dutch", "nl", "", "nl"), ("pl", "Polish", "pl", "", "pl2"),
    ("br", "Portuguese (Brazil)", "br", "", "br-abnt2"), ("pt", "Portuguese", "pt", "", "pt-latin1"),
    ("ch", "Swiss", "ch", "", "sg-latin1"), ("cz", "Czech", "cz", "", "cz"),
    ("tr", "Turkish", "tr", "", "trq"), ("ru", "Russian", "ru", "", "ru"),
]
DEAD = {"dead_grave": "̀", "dead_acute": "́", "dead_circumflex": "̂", "dead_tilde": "̃", "dead_diaeresis": "̈",
        "dead_abovering": "̊", "dead_caron": "̌", "dead_cedilla": "̧", "dead_macron": "̄", "dead_breve": "̆", "dead_doubleacute": "̋", "dead_ogonek": "̨", "dead_abovedot": "̇"}
KEYS = list(range(2, 14)) + [41] + list(range(16, 28)) + [43] + list(range(30, 41)) + [86] + list(range(44, 54))  # evdev codes

def ch(sym):
    if sym == 0: return None
    buf = ctypes.create_string_buffer(64); X.xkb_keysym_get_name(sym, buf, 64); name = buf.value.decode()
    if name in DEAD: return DEAD[name]
    if name.startswith("dead_"): return None
    u = X.xkb_keysym_to_utf32(sym)
    return chr(u) if u >= 32 and u != 127 else None

def table(layout, variant):
    ctx = X.xkb_context_new(0)
    n = Names(b"evdev", b"pc105", layout.encode(), variant.encode() or None, None)
    km = X.xkb_keymap_new_from_names(ctx, ctypes.byref(n), 0)
    if not km: raise SystemExit(f"no keymap for {layout}({variant})")
    rows = []
    for code in KEYS:
        lv = []
        for level in range(4):
            p = ctypes.POINTER(ctypes.c_uint32)()
            cnt = X.xkb_keymap_key_get_syms_by_level(km, code + 8, 0, level, ctypes.byref(p))
            lv.append(ch(p[0]) if cnt > 0 else None)
        rows.append((code, lv))
    return rows

def rs(c):
    if c is None: return "'\\0'"
    return "'" + {"'": "\\'", "\\": "\\\\"}.get(c, c) + "'" if c.isprintable() or c == " " else "'\\u{%x}'" % ord(c)

out = ["// Generated by tools/gen_keymaps.py from xkeyboard-config via libxkbcommon. Do not edit.", "",
       "/// (id, display name, xkb layout, xkb variant, console keymap)", "pub const LAYOUTS: &[(&str, &str, &str, &str, &str)] = &["]
for i, nm, lay, var, con in LAYOUTS: out.append(f'    ("{i}", "{nm}", "{lay}", "{var}", "{con}"),')
out += ["];", "", "/// Per layout, in `LAYOUTS` order: (evdev code, [plain, shift, altgr, shift+altgr]); '\\0' = nothing.",
        "pub const KEYMAPS: &[&[(u16, [char; 4])]] = &["]
for i, nm, lay, var, con in LAYOUTS:
    out.append(f"    // {nm}"); out.append("    &[")
    for code, lv in table(lay, var):
        out.append(f"        ({code}, [{', '.join(rs(c) for c in lv)}]),")
    out.append("    ],")
out.append("];")
import unicodedata
comp = []
for mark in sorted(set(DEAD.values())):
    for b in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ ":
        c = unicodedata.normalize("NFC", b + mark) if b != " " else None
        if c and len(c) == 1: comp.append((mark, b, c))
out += ["", "/// Dead-key compositions: (combining mark, base letter, result).", "pub const COMPOSE: &[(char, char, char)] = &["]
out += [f"    ({rs(m)}, {rs(b)}, {rs(c)})," for m, b, c in comp]
out.append("];")
Path(sys.argv[1] if len(sys.argv) > 1 else "springboard/src/installer/keymaps_data.rs").write_text("\n".join(out) + "\n")
print("layouts:", len(LAYOUTS))
